"""Patch review + PR opening."""

from __future__ import annotations

import secrets
from datetime import datetime, timezone
from pathlib import Path

from fastapi import APIRouter, HTTPException, status
from sqlalchemy import select

from .. import audit
from ..deps import CurrentUser, DBSession
from ..logging_config import get_logger
from ..models import Finding, PatchProposal, Project, PullRequest, Scan
from ..schemas import PatchProposalOut
from ..schemas_ext import OpenPRRequest, PatchDecision, PullRequestOut
from ..services.github import GitHubError, GitHubRepo, open_pull_request

log = get_logger(__name__)
router = APIRouter(tags=["patches"])


async def _get_patch(session, patch_id: str, user_id: str) -> PatchProposal:
    patch = (await session.execute(
        select(PatchProposal).where(PatchProposal.id == patch_id)
    )).scalar_one_or_none()
    if patch is None:
        raise HTTPException(404, detail="patch_not_found")
    proj = (await session.execute(
        select(Project)
        .join(Scan, Scan.project_id == Project.id)
        .join(Finding, Finding.scan_id == Scan.id)
        .where(Finding.id == patch.finding_id, Project.owner_id == user_id)
    )).scalar_one_or_none()
    if proj is None:
        raise HTTPException(404, detail="patch_not_found")
    return patch


@router.get("/patches/{patch_id}", response_model=PatchProposalOut)
async def get_patch(patch_id: str, user: CurrentUser,
                     session: DBSession) -> PatchProposal:
    return await _get_patch(session, patch_id, user.id)


@router.post("/patches/{patch_id}/decision", response_model=PatchProposalOut)
async def decide_patch(patch_id: str, payload: PatchDecision,
                        user: CurrentUser,
                        session: DBSession) -> PatchProposal:
    patch = await _get_patch(session, patch_id, user.id)
    if patch.status not in {"pending_review"}:
        raise HTTPException(409, detail=f"already_{patch.status}")
    patch.status = payload.status
    patch.reviewer_id = user.id
    patch.decided_at = datetime.now(timezone.utc)
    await audit.record(session, actor_id=user.id, action=f"patch.{payload.status}",
                        target_type="patch", target_id=patch.id)
    await session.commit()
    await session.refresh(patch)
    return patch


@router.post("/patches/{patch_id}/pull-request", response_model=PullRequestOut,
             status_code=status.HTTP_201_CREATED)
async def open_pr(patch_id: str, payload: OpenPRRequest, user: CurrentUser,
                   session: DBSession) -> PullRequest:
    patch = await _get_patch(session, patch_id, user.id)
    if patch.status != "approved":
        raise HTTPException(409, detail="patch_must_be_approved")
    if not patch.patched_source:
        raise HTTPException(409, detail="patch_has_no_source")

    # We need the original file path from the finding.
    finding = (await session.execute(
        select(Finding).where(Finding.id == patch.finding_id))
    ).scalar_one()

    branch = f"{payload.branch_prefix}/{patch.id[:8]}-{secrets.token_hex(3)}"
    title = payload.title or f"IR-SAM: fix {finding.cwe} in {finding.file_path}"
    body = payload.body or (
        f"Automated patch generated by IR-SAM.\n\n"
        f"- CWE: {finding.cwe}\n"
        f"- Rule: {finding.rule_id}\n"
        f"- File: {finding.file_path}:{finding.line}\n"
        f"- Stage reached: {patch.stage_reached}\n"
    )

    try:
        result = await open_pull_request(
            token=payload.token,
            repo=GitHubRepo(owner=payload.repo_owner, repo=payload.repo_name,
                             default_branch=payload.base_branch),
            branch=branch,
            files={finding.file_path: patch.patched_source},
            title=title,
            body=body,
        )
    except GitHubError as exc:
        log.warning("github_pr_failed", patch_id=patch.id, error=str(exc))
        raise HTTPException(status_code=502, detail=f"github_error: {exc}") from exc

    pr = PullRequest(
        patch_proposal_id=patch.id,
        provider="github",
        remote_id=str(result.get("number")) if result.get("number") else None,
        url=result.get("html_url"),
        status="open",
    )
    session.add(pr)
    patch.status = "merged" if result.get("merged") else patch.status
    await audit.record(session, actor_id=user.id, action="pull_request.opened",
                        target_type="patch", target_id=patch.id,
                        payload={"repo": f"{payload.repo_owner}/{payload.repo_name}",
                                 "url": result.get("html_url")})
    await session.commit()
    await session.refresh(pr)
    return pr


@router.post("/patches/{patch_id}/apply", response_model=PatchProposalOut)
async def apply_patch(patch_id: str, user: CurrentUser,
                       session: DBSession) -> PatchProposal:
    """Write the patched source to disk and mark the patch as applied.

    This replaces the GitHub-PR workflow for users who want the fix applied
    in place. The destination is the original ``finding.file_path``.
    """
    patch = await _get_patch(session, patch_id, user.id)
    if patch.status != "approved":
        raise HTTPException(409, detail="patch_must_be_approved")
    if not patch.patched_source:
        raise HTTPException(409, detail="patch_has_no_source")

    finding = (await session.execute(
        select(Finding).where(Finding.id == patch.finding_id))
    ).scalar_one()

    target = Path(finding.file_path)
    # Safety: only overwrite existing files; never create new ones at arbitrary paths.
    if not target.is_file():
        raise HTTPException(409, detail=f"target_file_not_found: {target}")

    try:
        # Preserve a one-shot backup next to the file.
        backup = target.with_suffix(target.suffix + ".irsam.bak")
        if not backup.exists():
            backup.write_bytes(target.read_bytes())
        target.write_text(patch.patched_source, encoding="utf-8")
    except OSError as exc:
        log.warning("apply_patch_failed", patch_id=patch.id, error=str(exc))
        raise HTTPException(status_code=500, detail=f"write_failed: {exc}") from exc

    patch.status = "applied"
    await audit.record(session, actor_id=user.id, action="patch.applied",
                        target_type="patch", target_id=patch.id,
                        payload={"file_path": str(target)})
    await session.commit()
    await session.refresh(patch)
    return patch
